const tinyBzip2 = "QlpoOTFBWSZTWWNaHKMAAAXfgAAQQAMgACJjDCQGJYwgIAAhqm1NqepiYyI8oUGjRoMgNJqmKCO3agrnKsFNmBJIevBS5d/sHOPxdyRThQkGNaHKMA=="

func writeFile(t *testing.T, path string, data []byte) {
	t.Helper()
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(path, data, 0o600); err != nil {
		t.Fatal(err)
	}
}

func gzipped(t *testing.T, text string) []byte {
	t.Helper()
	var buf bytes.Buffer
	w := gzip.NewWriter(&buf)
	if _, err := w.Write([]byte(text)); err != nil {
		t.Fatal(err)
	}
	if err := w.Close(); err != nil {
		t.Fatal(err)
	}
	return buf.Bytes()
}

func TestLookupReadsInstalledPages(t *testing.T) {
	t.Parallel()

	first, second := t.TempDir(), t.TempDir()
	writeFile(t, filepath.Join(first, "man1", "list.1.gz"), gzipped(t, listPage))
	writeFile(t, filepath.Join(first, "man1", "ls.1"), []byte(".so man1/list.1\n"))
	writeFile(t, filepath.Join(first, "man8", "list.8"), []byte(".TH LIST 8\n.SH NAME\nlist \\- the admin page\n"))
	bz, err := base64.StdEncoding.DecodeString(tinyBzip2)
	if err != nil {
		t.Fatal(err)
	}
	writeFile(t, filepath.Join(second, "man8", "tiny.8.bz2"), bz)
	writeFile(t, filepath.Join(second, "man1", "packed.1.xz"), []byte("not readable without xz"))
	writeFile(t, filepath.Join(second, "man1", "escape.1"), []byte(".so ../../outside.1\n"))

	l := NewLookup(first+string(os.PathListSeparator)+second, "")
	for name, summary := range map[string]string{
		"list": "list - show directory entries",
		"ls":   "list - show directory entries",
		"tiny": "tiny - does little",
	} {
		page, err := l.Page(t.Context(), name)
		if err != nil || page.Summary != summary {
			t.Errorf("Page(%s) = %q, %v; want %q", name, page.Summary, err, summary)
		}
	}
	for _, name := range []string{"packed", "escape", "missing", "-rf", "../etc/passwd", "a b", ""} {
		if _, err := l.Page(t.Context(), name); !errors.Is(err, ErrNoPage) {
			t.Errorf("Page(%q) error = %v, want ErrNoPage", name, err)
		}
	}
}

func TestLookupCachesOnlyInstalledPagesUnderTheirOwnKeys(t *testing.T) {
	t.Parallel()

	dir := t.TempDir()
	writeFile(t, filepath.Join(dir, "man1", "list.1.gz"), gzipped(t, listPage))
	l := NewLookup(dir, "")
	for i := range 1000 {
		if _, err := l.Page(t.Context(), fmt.Sprintf("missing%d", i)); !errors.Is(err, ErrNoPage) {
			t.Fatalf("Page(missing%d) error = %v, want ErrNoPage", i, err)
		}
	}
	pinned := perf.PinsSource("list", func(name string) {
		if _, err := l.Page(t.Context(), name); err != nil {
			t.Fatal(err)
		}
	})
	if pinned {
		t.Error("the cached name keeps the text it was sliced from alive")
	}
	if len(l.cache) != 1 {
		t.Errorf("cache holds %d entries, want only the installed page", len(l.cache))
	}
}

func TestManDirsFromPath(t *testing.T) {
	t.Parallel()

	got := manDirs("", "/opt/tool/bin"+string(os.PathListSeparator)+"/usr/bin")
	for _, want := range []string{"/opt/tool/share/man", "/opt/tool/man", "/usr/share/man"} {
		if !slices.Contains(got, want) {
			t.Errorf("manDirs = %v, missing %s", got, want)
		}
	}
	if got := manDirs("/custom", "/opt/tool/bin"); !slices.Equal(got, []string{"/custom"}) {
		t.Errorf("explicit MANPATH = %v", got)
	}
	if got := manDirs("/custom:", "/opt/tool/bin"); !slices.Contains(got, "/opt/tool/share/man") || got[0] != "/custom" {
		t.Errorf("MANPATH with an empty entry = %v, want defaults appended", got)
	}
}

func TestRealManPage(t *testing.T) {
	t.Parallel()

	page, err := NewLookup(os.Getenv("MANPATH"), os.Getenv("PATH")).Page(t.Context(), "ls")
	if errors.Is(err, ErrNoPage) {
		t.Skip("no ls manual page installed")
	}
	if err != nil {
		t.Fatalf("Page(ls) error = %v", err)
	}
	if !strings.HasPrefix(page.Summary, "ls") || len(page.Options()) < 10 {
		t.Errorf("Summary = %q, %d options", page.Summary, len(page.Options()))
	}
}
