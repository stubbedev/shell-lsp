package gitrepo

import "testing"

func TestWildmatchFollowsGitWithPathnames(t *testing.T) {
	t.Parallel()

	tests := []struct {
		match, foldMatch bool
		text, pattern    string
	}{
		{true, true, "foo", "foo"},
		{false, false, "foo", "bar"},
		{true, true, "", ""},
		{true, true, "foo", "???"},
		{false, false, "foo", "??"},
		{true, true, "foo", "*"},
		{true, true, "foo", "f*"},
		{false, false, "foo", "*f"},
		{true, true, "foo", "*foo*"},
		{true, true, "foobar", "*ob*a*r*"},
		{true, true, "aaaaaaabababab", "*ab"},
		{true, true, "foo*", `foo\*`},
		{false, false, "foobar", `foo\*bar`},
		{true, true, `f\oo`, `f\\oo`},
		{true, true, "ball", "*[al]?"},
		{false, false, "ten", "[ten]"},
		{true, true, "ten", "**[!te]"},
		{false, false, "ten", "**[!ten]"},
		{true, true, "ten", "t[a-g]n"},
		{false, false, "ten", "t[!a-g]n"},
		{true, true, "ton", "t[!a-g]n"},
		{true, true, "ton", "t[^a-g]n"},
		{true, true, "a]b", "a[]]b"},
		{true, true, "a-b", "a[]-]b"},
		{true, true, "a]b", "a[]-]b"},
		{false, false, "aab", "a[]-]b"},
		{true, true, "aab", "a[]a-]b"},
		{true, true, "]", "]"},
		{false, false, "foo/baz/bar", "foo*bar"},
		{false, false, "foo/baz/bar", "foo**bar"},
		{true, true, "foobazbar", "foo**bar"},
		{true, true, "foo/baz/bar", "foo/**/bar"},
		{true, true, "foo/baz/bar", "foo/**/**/bar"},
		{true, true, "foo/b/a/z/bar", "foo/**/bar"},
		{true, true, "foo/b/a/z/bar", "foo/**/**/bar"},
		{true, true, "foo/bar", "foo/**/bar"},
		{true, true, "foo/bar", "foo/**/**/bar"},
		{false, false, "foo/bar", "foo?bar"},
		{false, false, "foo/bar", "foo[/]bar"},
		{false, false, "foo/bar", "foo[^a-z]bar"},
		{false, false, "foo/bar", "f[^eiu][^eiu][^eiu][^eiu][^eiu]r"},
		{true, true, "foo-bar", "f[^eiu][^eiu][^eiu][^eiu][^eiu]r"},
		{true, true, "foo", "**/foo"},
		{true, true, "XXX/foo", "**/foo"},
		{true, true, "bar/baz/foo", "**/foo"},
		{false, false, "bar/baz/foo", "*/foo"},
		{false, false, "foo/bar/baz", "**/bar*"},
		{true, true, "deep/foo/bar/baz", "**/bar/*"},
		{false, false, "deep/foo/bar/baz/", "**/bar/*"},
		{true, true, "deep/foo/bar/baz/", "**/bar/**"},
		{false, false, "deep/foo/bar", "**/bar/*"},
		{true, true, "deep/foo/bar/", "**/bar/**"},
		{false, false, "foo/bar/baz", "**/bar**"},
		{true, true, "foo/bar/baz/x", "*/bar/**"},
		{false, false, "deep/foo/bar/baz/x", "*/bar/**"},
		{true, true, "deep/foo/bar/baz/x", "**/bar/*/*"},
		{false, false, "acrt", "a[c-c]st"},
		{true, true, "acrt", "a[c-c]rt"},
		{false, false, "]", "[!]-]"},
		{true, true, "a", "[!]-]"},
		{false, false, "", `\`},
		{false, false, `\`, `\`},
		{false, false, `XXX/\`, `*/\`},
		{true, true, `XXX/\`, `*/\\`},
		{true, true, "[ab]", `\[ab]`},
		{true, true, "[ab]", "[[]ab]"},
		{true, true, "[ab]", "[[:]ab]"},
		{false, false, "[ab]", "[[::]ab]"},
		{true, true, "[ab]", "[[:digit]ab]"},
		{true, true, "[ab]", `[\[:]ab]`},
		{true, true, "?a?b", `\??\?b`},
		{true, true, "abc", `\a\b\c`},
		{false, false, "foo", ""},
		{true, true, "foo/bar/baz/to", "**/t[o]"},
		{true, true, "a1B", "[[:alpha:]][[:digit:]][[:upper:]]"},
		{false, true, "a", "[[:digit:][:upper:][:space:]]"},
		{true, true, "A", "[[:digit:][:upper:][:space:]]"},
		{true, true, "1", "[[:digit:][:upper:][:space:]]"},
		{false, false, "1", "[[:digit:][:upper:][:spaci:]]"},
		{true, true, " ", "[[:digit:][:upper:][:space:]]"},
		{false, false, ".", "[[:digit:][:upper:][:space:]]"},
		{true, true, ".", "[[:digit:][:punct:][:space:]]"},
		{true, true, "5", "[[:xdigit:]]"},
		{true, true, "f", "[[:xdigit:]]"},
		{true, true, "D", "[[:xdigit:]]"},
		{false, true, "a", "[A-Z]"},
		{true, true, "A", "[A-Z]"},
		{false, true, "A", "[a-z]"},
		{true, true, "a", "[a-z]"},
		{false, true, "a", "[[:upper:]]"},
		{true, true, "A", "[[:upper:]]"},
		{false, true, "A", "[[:lower:]]"},
		{true, true, "a", "[[:lower:]]"},
		{false, true, "A", "[B-Za]"},
		{true, true, "a", "[B-Za]"},
		{false, true, "A", "[B-a]"},
		{true, true, "a", "[B-a]"},
		{false, true, "z", "[Z-y]"},
		{true, true, "Z", "[Z-y]"},
		{false, true, "FOO/bar", "foo/*"},
	}
	for _, tt := range tests {
		if got := wildmatch(tt.pattern, tt.text, false); got != tt.match {
			t.Errorf("wildmatch(%q, %q) = %v, want %v", tt.pattern, tt.text, got, tt.match)
		}
		if got := wildmatch(tt.pattern, tt.text, true); got != tt.foldMatch {
			t.Errorf("wildmatch(%q, %q) folding case = %v, want %v", tt.pattern, tt.text, got, tt.foldMatch)
		}
	}
}
