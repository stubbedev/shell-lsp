package main

import (
	"context"
	"errors"
	"flag"
	"fmt"
	"os"
	"os/exec"
	"regexp"
	"slices"
	"strconv"
	"strings"

	"github.com/stubbedev/shell-lsp/internal/atomicfile"
	"github.com/stubbedev/shell-lsp/internal/corpus"
	"github.com/stubbedev/shell-lsp/internal/lint"
)

const (
	shellcheckVersion  = "0.11.0"
	failureExamples    = 5
	parityBaselineFile = "corpus/shellcheck.md"
)

var (
	parityRow     = regexp.MustCompile(`^\| (SC\d+) \| (\d+) \| (\d+) \| (\d+) \|$`)
	paritySummary = regexp.MustCompile(`^(\d+) scripts compared, (\d+) skipped as not UTF-8 or with CRLF line endings\.$`)
	parityCrash   = regexp.MustCompile("^- `([^`]+)`$")
)

type parity struct {
	compared, skipped int
	crashed           []string
	tallies           map[lint.Code]tally
}

func runShellcheck(ctx context.Context, args []string) error {
	fs := flag.NewFlagSet("shellcheck", flag.ContinueOnError)
	var c corpusFlags
	c.register(fs)
	baselineFile := fs.String("baseline", parityBaselineFile, "baseline to compare with or rewrite")
	update := fs.Bool("update", false, "rewrite the baseline instead of comparing with it")
	if err := parseFlags(fs, args); err != nil {
		return err
	}
	if fs.NArg() != 0 {
		return errUsage
	}
	if err := requireShellcheck(ctx); err != nil {
		return err
	}
	repos, err := c.fetched()
	if err != nil {
		return err
	}
	listing, err := corpus.Scripts(repos, c.cache)
	if err != nil {
		return err
	}
	cmp, err := compareWithShellcheck(ctx, listing)
	if err != nil {
		return err
	}
	got := parity{compared: cmp.compared, skipped: cmp.skipped, crashed: cmp.crashed, tallies: cmp.tallies}
	if *update {
		return atomicfile.Write(*baselineFile, []byte(renderParity(got)))
	}
	raw, err := os.ReadFile(*baselineFile)
	if err != nil {
		return fmt.Errorf("reading the ShellCheck baseline: %w", err)
	}
	want, err := parseParity(string(raw))
	if err != nil {
		return fmt.Errorf("%s: %w", *baselineFile, err)
	}
	problems := diffParity(want, got)
	if len(problems) == 0 {
		fmt.Printf("%d scripts match %s\n", got.compared, *baselineFile)
		return nil
	}
	for _, p := range problems {
		fmt.Println(p.message)
		if p.regressed {
			printExamples(cmp.mismatches, p.code)
		}
	}
	return fmt.Errorf("the corpus no longer matches %s; fix the regressions, or run `just corpus-baseline` and review the diff", *baselineFile)
}

func printExamples(mismatches []mismatch, code lint.Code) {
	shown := map[side]int{}
	for _, m := range mismatches {
		if m.code != code || shown[m.side] >= failureExamples {
			continue
		}
		shown[m.side]++
		fmt.Println(m)
	}
}

func requireShellcheck(ctx context.Context) error {
	out, err := exec.CommandContext(ctx, "shellcheck", "--version").Output()
	if err != nil {
		return fmt.Errorf("running shellcheck --version: %w", err)
	}
	for line := range strings.SplitSeq(string(out), "\n") {
		if v, ok := strings.CutPrefix(line, "version: "); ok {
			if v != shellcheckVersion {
				return fmt.Errorf("the baseline is recorded with shellcheck %s, but %s is on PATH; use `nix develop`", shellcheckVersion, v)
			}
			return nil
		}
	}
	return fmt.Errorf("shellcheck --version printed no version: %q", out)
}

func renderParity(p parity) string {
	var b strings.Builder
	b.WriteString("# ShellCheck parity on the corpus\n\n")
	b.WriteString("Generated by `just corpus-baseline` from the scripts of the repositories in\n")
	b.WriteString("[repos.txt](repos.txt), compared with ShellCheck " + shellcheckVersion + " as described in\n")
	b.WriteString("[docs/corpus.md](../docs/corpus.md). A finding agrees when both report the same code at the\n")
	b.WriteString("same line and column. CI fails when any number here changes.\n\n")
	fmt.Fprintf(&b, "%d scripts compared, %d skipped as not UTF-8 or with CRLF line endings.\n\n", p.compared, p.skipped)
	if len(p.crashed) > 0 {
		b.WriteString("ShellCheck fails with an internal error on these scripts, which are left out:\n\n")
		for _, path := range p.crashed {
			b.WriteString("- `" + path + "`\n")
		}
		b.WriteString("\n")
	}
	b.WriteString("| Code | Agree | Ours only | ShellCheck only |\n")
	b.WriteString("| --- | --- | --- | --- |\n")
	for _, code := range implementedCodes() {
		t := p.tallies[code]
		fmt.Fprintf(&b, "| %s | %d | %d | %d |\n", code, t.agree, t.oursOnly, t.theirsOnly)
	}
	return b.String()
}

func parseParity(text string) (parity, error) {
	p := parity{tallies: map[lint.Code]tally{}}
	summary := false
	for n, line := range strings.Split(text, "\n") {
		if m := paritySummary.FindStringSubmatch(line); m != nil {
			p.compared, p.skipped = atoi(m[1]), atoi(m[2])
			summary = true
			continue
		}
		if m := parityCrash.FindStringSubmatch(line); m != nil {
			p.crashed = append(p.crashed, m[1])
			continue
		}
		m := parityRow.FindStringSubmatch(line)
		if m == nil {
			continue
		}
		code, err := lint.ParseCode(m[1])
		if err != nil {
			return parity{}, fmt.Errorf("line %d: %w", n+1, err)
		}
		if _, dup := p.tallies[code]; dup {
			return parity{}, fmt.Errorf("line %d: %s is listed twice", n+1, code)
		}
		p.tallies[code] = tally{agree: atoi(m[2]), oursOnly: atoi(m[3]), theirsOnly: atoi(m[4])}
	}
	if !summary {
		return parity{}, errors.New("no \"N scripts compared, M skipped ...\" line")
	}
	return p, nil
}

func atoi(s string) int {
	n, err := strconv.Atoi(s)
	if err != nil {
		panic(fmt.Sprintf("lintcheck: %q matched a digits pattern: %v", s, err))
	}
	return n
}

type parityProblem struct {
	code      lint.Code
	regressed bool
	message   string
}

func diffParity(want, got parity) []parityProblem {
	var out []parityProblem
	if want.compared != got.compared || want.skipped != got.skipped || !slices.Equal(want.crashed, got.crashed) {
		out = append(out, parityProblem{message: fmt.Sprintf(
			"corpus: the baseline compared %d scripts, skipped %d and saw ShellCheck crash on %d; now %d, %d and %d",
			want.compared, want.skipped, len(want.crashed), got.compared, got.skipped, len(got.crashed))})
	}
	codes := implementedCodes()
	for code := range want.tallies {
		if !slices.Contains(codes, code) {
			codes = append(codes, code)
		}
	}
	slices.Sort(codes)
	for _, code := range codes {
		w, g := want.tallies[code], got.tallies[code]
		if w == g {
			continue
		}
		regressed := g.agree < w.agree || g.oursOnly > w.oursOnly || g.theirsOnly > w.theirsOnly
		verdict := "improved; refresh the baseline"
		if regressed {
			verdict = "REGRESSED"
		}
		out = append(out, parityProblem{code: code, regressed: regressed, message: fmt.Sprintf(
			"%s %s: agree %d -> %d, ours only %d -> %d, ShellCheck only %d -> %d",
			code, verdict, w.agree, g.agree, w.oursOnly, g.oursOnly, w.theirsOnly, g.theirsOnly)})
	}
	return out
}
