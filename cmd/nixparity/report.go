const bytesPerMiB = 1 << 20

func tableRow(cells ...string) string {
	return "| " + strings.Join(cells, " | ") + " |\n"
}

func table(b *strings.Builder, header []string, rows [][]string) {
	b.WriteString(tableRow(header...))
	delimiter := make([]string, len(header))
	for i := range delimiter {
		delimiter[i] = "---"
	}
	b.WriteString(tableRow(delimiter...))
	for _, row := range rows {
		b.WriteString(tableRow(row...))
	}
	b.WriteString("\n")
}

func cells(values ...int) []string {
	out := make([]string, len(values))
	for i, v := range values {
		out[i] = strconv.Itoa(v)
	}
	return out
}

func serverLabel(i identity) string {
	if i.Version == "" {
		return i.Name
	}
	return i.Name + " " + i.Version
}

func renderMarkdown(r report) string {
	var b strings.Builder
	scope := r.Counts.Scope
	ours, theirs := serverLabel(r.Ours.Server), serverLabel(r.Theirs.Server)
	fmt.Fprintf(&b, "# Nix server parity on %s\n\n", scope.Project)
	fmt.Fprintf(&b, "%s against %s: %d files, up to %d positions per file (limit %d files), seed %d.\n\n", ours, theirs, scope.Files, scope.Positions, scope.FileLimit, scope.Seed)
	b.WriteString("Generated by `cmd/nixparity` as described in docs/corpus.md. It records counts and positions only.\n\n")
	if len(r.Counts.Skipped) > 0 {
		b.WriteString("Skipped as too large or not UTF-8:\n\n")
		for _, rel := range r.Counts.Skipped {
			fmt.Fprintf(&b, "- `%s`\n", rel)
		}
		b.WriteString("\n")
	}
	b.WriteString("## Agreement\n\n")
	renderAgreement(&b, r.Counts.Features)
	b.WriteString("## Answer items\n\n")
	renderItems(&b, r.Counts.Features)
	fmt.Fprintf(&b, "## Outcomes of %s\n\n", ours)
	renderOutcomes(&b, r.Counts.Features, func(c featureCounts) sideTally { return c.Ours })
	fmt.Fprintf(&b, "## Outcomes of %s\n\n", theirs)
	renderOutcomes(&b, r.Counts.Features, func(c featureCounts) sideTally { return c.Theirs })
	fmt.Fprintf(&b, "## Latency of %s\n\n", ours)
	renderLatency(&b, r.Ours.Latency)
	fmt.Fprintf(&b, "## Latency of %s\n\n", theirs)
	renderLatency(&b, r.Theirs.Latency)
	b.WriteString("## Memory and restarts\n\n")
	table(&b, []string{"Server", "Peak RSS", "Restarts"}, [][]string{
		{ours, formatRSS(r.Ours.PeakRSSBytes), strconv.Itoa(r.Ours.Restarts)},
		{theirs, formatRSS(r.Theirs.PeakRSSBytes), strconv.Itoa(r.Theirs.Restarts)},
	})
	if len(r.Examples) > 0 {
		b.WriteString("## Examples\n\n")
		for _, e := range r.Examples {
			fmt.Fprintf(&b, "- %s\n", e)
		}
	}
	return b.String()
}

func renderAgreement(b *strings.Builder, features []featureCounts) {
	rows := make([][]string, 0, len(features))
	for _, c := range features {
		rows = append(rows, append([]string{c.Feature.String()}, cells(c.Queries, c.Agree, c.Disagree, c.BothEmpty, c.OursMissing, c.TheirsMissing, c.Failed)...))
	}
	table(b, []string{"Feature", "Queries", "Agree", "Disagree", "Both empty", "Ours missing", "Theirs missing", "Failed"}, rows)
}

func renderItems(b *strings.Builder, features []featureCounts) {
	rows := make([][]string, 0, len(features))
	for _, c := range features {
		rows = append(rows, append([]string{c.Feature.String()}, cells(c.Items.Shared, c.Items.OursOnly, c.Items.TheirsOnly)...))
	}
	table(b, []string{"Feature", "Shared", "Ours only", "Theirs only"}, rows)
}

func renderOutcomes(b *strings.Builder, features []featureCounts, side func(featureCounts) sideTally) {
	rows := make([][]string, 0, len(features))
	for _, c := range features {
		t := side(c)
		rows = append(rows, append([]string{c.Feature.String()}, cells(t.Answered, t.Empty, t.Refused, t.Unsupported, t.Silent, t.Malformed, t.Timeout, t.Crashed)...))
	}
	table(b, []string{"Feature", "Answered", "Empty", "Refused", "Unsupported", "Silent", "Malformed", "Timeout", "Crashed"}, rows)
}

func renderLatency(b *strings.Builder, summaries []latencySummary) {
	rows := make([][]string, 0, len(summaries))
	for _, s := range summaries {
		rows = append(rows, []string{
			s.Feature.String(),
			strconv.Itoa(s.Samples),
			strconv.FormatInt(s.P50Micros, 10),
			strconv.FormatInt(s.P90Micros, 10),
			strconv.FormatInt(s.P99Micros, 10),
			strconv.FormatInt(s.MaxMicros, 10),
		})
	}
	table(b, []string{"Feature", "Samples", "p50 (us)", "p90 (us)", "p99 (us)", "Max (us)"}, rows)
}

func formatRSS(peak *int64) string {
	if peak == nil {
		return "not measured"
	}
	return fmt.Sprintf("%.1f MiB", float64(*peak)/bytesPerMiB)
}

func encodeJSON(v any) ([]byte, error) {
	raw, err := json.MarshalIndent(v, "", "  ")
	if err != nil {
		return nil, fmt.Errorf("encoding the report: %w", err)
	}
	return append(raw, '\n'), nil
}

func parseBaseline(raw []byte) (counts, error) {
	decoder := json.NewDecoder(bytes.NewReader(raw))
	decoder.DisallowUnknownFields()
	var c counts
	if err := decoder.Decode(&c); err != nil {
		return counts{}, err
	}
	if _, err := decoder.Token(); !errors.Is(err, io.EOF) {
		return counts{}, errors.New("more than one JSON value")
	}
	return c, nil
}

type drift struct {
	feature   feature
	regressed bool
	message   string
}

func diffCounts(want, got counts) []drift {
	var out []drift
	if want.Scope != got.Scope || !slices.Equal(want.Skipped, got.Skipped) {
		out = append(out, drift{message: fmt.Sprintf("scope: the baseline has %+v with %d skipped; now %+v with %d skipped", want.Scope, len(want.Skipped), got.Scope, len(got.Skipped))})
	}
	for _, f := range allFeatures() {
		w, g := countsOf(want, f), countsOf(got, f)
		if w == g {
			continue
		}
		regressed := g.Agree < w.Agree || g.Disagree > w.Disagree || g.OursMissing > w.OursMissing || g.Failed > w.Failed
		label := "improved or moved; refresh the baseline"
		if regressed {
			label = "REGRESSED"
		}
		out = append(out, drift{feature: f, regressed: regressed, message: fmt.Sprintf(
			"%s %s: agree %d -> %d, disagree %d -> %d, both empty %d -> %d, ours missing %d -> %d, theirs missing %d -> %d, failed %d -> %d",
			f, label, w.Agree, g.Agree, w.Disagree, g.Disagree, w.BothEmpty, g.BothEmpty, w.OursMissing, g.OursMissing, w.TheirsMissing, g.TheirsMissing, w.Failed, g.Failed)})
	}
	return out
}

func countsOf(c counts, f feature) featureCounts {
	i := slices.IndexFunc(c.Features, func(entry featureCounts) bool { return entry.Feature == f })
	if i < 0 {
		return featureCounts{Feature: f}
	}
	return c.Features[i]
}
